#!/usr/bin/env node
/**
 * Generates src/translations/generated.ts from src/translations/<locale>/<namespace>.json.
 * A file's name is its top-level key: en/paywall.json → t('paywall.…'). Run after adding or
 * renaming a translation file (`npm run gen:i18n`); `lint:translations` fails when the
 * committed file is stale. Locales with no files yet are left out and fall back to `en`.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'translations');
const locales = JSON.parse(readFileSync(join(root, 'locales.json'), 'utf8'));

const ident = (s) => s.replace(/[^A-Za-z0-9]/g, '_');
const lines = ['/* eslint-disable */', '// Generated by scripts/gen-translations.mjs — do not edit.', ''];
const bodies = [];

for (const locale of locales) {
  const dir = join(root, locale);
  if (!existsSync(dir)) continue;
  const namespaces = readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.replace(/\.json$/, ''))
    .sort();
  if (namespaces.length === 0) continue;
  for (const ns of namespaces) lines.push(`import ${ident(locale)}_${ident(ns)} from './${locale}/${ns}.json';`);
  bodies.push(
    `  '${locale}': { translation: { ${namespaces.map((ns) => `${JSON.stringify(ns)}: ${ident(locale)}_${ident(ns)}`).join(', ')} } },`,
  );
}

lines.push('', 'export const resources = {', ...bodies, '} as const;', '');
lines.push('export type EnTranslation = (typeof resources)[\'en\'][\'translation\'];', '');
const output = lines.join('\n');
const target = join(root, 'generated.ts');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    process.stderr.write('src/translations/generated.ts is stale: run `npm run gen:i18n`\n');
    process.exit(1);
  }
  process.stdout.write('ok generated.ts is current\n');
} else {
  writeFileSync(target, output);
  process.stdout.write(`wrote generated.ts (${bodies.length} locales)\n`);
}
